# ------------------------------------------------------------------- derived data
def build_shot_table():
    rows, t = [], 0.0
    for sid, title, s0, s1, shots in SCENES:
        for i, (img, dur, cam, opt) in enumerate(shots, 1):
            rows.append(dict(
                sid=sid, num=i, image=img, start=t, dur=dur, cam=cam, **opt))
            t += dur
    return rows, t

SHOTS, TOTAL = build_shot_table()

def tc(sec):
    m = int(sec // 60); s = sec - m * 60
    return f"{m:02d}:{s:06.3f}".replace(".", ":", 0) if False else f"{m:02d}:{int(s):02d}.{int(round((s-int(s))*1000)):03d}"

if __name__ == "__main__":
    rows, total = build_shot_table()
    print(f"shots={len(rows)}  total={total:.3f}s  ({int(total//60)}:{total%60:06.3f})")
    for sid, title, s0, s1, shots in SCENES:
        sub = [r for r in rows if r["sid"] == sid]
        print(f"  scene {sid}: {title:28s} {s0:6.1f}-{s1:6.1f} "
              f"({s1-s0:5.1f}s, {len(sub)} shots, sum={sum(r['dur'] for r in sub):.1f})")
    assert abs(total - 780.0) < 1e-6, total
    for sid, title, s0, s1, shots in SCENES:
        assert abs(sum(x[1] for x in shots) - (s1 - s0)) < 1e-6, (sid, sum(x[1] for x in shots), s1 - s0)
    print("OK: 13:00 ровно")
