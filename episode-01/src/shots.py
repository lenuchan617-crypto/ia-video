def push(s=0.16, cx=0.5, cy=0.5):      # медленный наезд
    return (1.0, 1.0 + s, cx, cy, cx, cy)

def pull(s=0.16, cx=0.5, cy=0.5):      # отъезд
    return (1.0 + s, 1.0, cx, cy, cx, cy)

def pan(x0, x1, z=1.12, y=0.5):        # панорама слева-направо
    return (z, z, x0, y, x1, y)

def tilt(y0, y1, z=1.12, x=0.5):       # тилт вверх/вниз
    return (z, z, x, y0, x, y1)

def drift(z0, z1, c0, c1):             # произвольный дрейф
    return (z0, z1, c0[0], c0[1], c1[0], c1[1])

